def get_display_number(track_id):

    global NEXT_PLAYER_NUMBER

    if track_id == -1:
        return 0

    if track_id not in PLAYER_DISPLAY_NUMBER:

        PLAYER_DISPLAY_NUMBER[track_id] = NEXT_PLAYER_NUMBER

        NEXT_PLAYER_NUMBER += 1

    return PLAYER_DISPLAY_NUMBER[track_id]


