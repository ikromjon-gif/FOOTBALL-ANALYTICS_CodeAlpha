# 17. DRAW METEOR BALL
# ============================================================

def draw_meteor_ball(
    frame,
    position,
    velocity
):

    if position is None:
        return


    x, y = int(position[0]), int(position[1])

    vx = velocity[0]
    vy = velocity[1]

    speed = math.sqrt(
        vx * vx +
        vy * vy
    )


    # --------------------------------------------------------
    # Meteor tail faqat harakat bo'lsa
    # --------------------------------------------------------

    if speed > 2:

        # Direction normalize

        dx = vx / speed
        dy = vy / speed


        # Fire tail harakatning TESKARI tomonida

        tail_length = min(
            45,
            max(
                15,
                int(speed * 3)
            )
        )


        # Faqat 6 ta qisqa segment
        # HECH QACHON eski frame bilan ulanmaydi

        for i in range(6, 0, -1):

            ratio = i / 6.0

            tx = int(
                x - dx * tail_length * ratio
            )

            ty = int(
                y - dy * tail_length * ratio
            )


            radius = max(
                2,
                int(7 * (1 - ratio))
            )


            # Outer fire
            cv2.circle(

                frame,

                (tx, ty),

                radius + 2,

                (0, 100, 255),

                -1,

                cv2.LINE_AA
            )


            # Inner yellow
            cv2.circle(

                frame,

                (tx, ty),

                radius,

                (0, 220, 255),

                -1,

                cv2.LINE_AA
            )


    # --------------------------------------------------------
    # BALL CENTER
    # --------------------------------------------------------

    # Outer glow
    cv2.circle(

        frame,

        (x, y),

        11,

        (0, 150, 255),

        2,

        cv2.LINE_AA
    )


    # Main ball marker
    cv2.circle(

        frame,

        (x, y),

        7,

        (0, 230, 255),

        -1,

        cv2.LINE_AA
    )


    # Bright center
    cv2.circle(

        frame,

        (x, y),

        3,

        (255, 255, 255),

        -1,

        cv2.LINE_AA
    )


