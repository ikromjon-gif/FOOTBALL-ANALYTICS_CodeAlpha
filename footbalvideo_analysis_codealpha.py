def select_best_ball(
    ball_candidates,
    previous_position
):

    if len(ball_candidates) == 0:
        return None


    # Previous position yo'q bo'lsa
    # eng yuqori confidence

    if previous_position is None:

        return max(
            ball_candidates,
            key=lambda x: x[2]
        )


    best_candidate = None

    best_score = -999999


    for x, y, conf in ball_candidates:

        distance = math.dist(
            previous_position,
            (x, y)
        )


        # Confidence + previous positionga yaqinlik

        score = (
            conf * 100
            -
            distance * 0.08
        )


        if score > best_score:

            best_score = score

            best_candidate = (
                x,
                y,
                conf,
                distance
            )


    return best_candidate


