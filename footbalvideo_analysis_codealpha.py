# 15. DRAW MODERN ID BADGE
# ============================================================

def draw_id_badge(
    frame,
    x1,
    y1,
    x2,
    player_class,
    display_number
):

    color = COLORS.get(
        player_class,
        COLORS["UNKNOWN"]
    )


    # -----------------------------------------
    # Compact label
    # -----------------------------------------

    if player_class == "IRAN":

        label = f"IRN {display_number}"

    elif player_class == "UZBEKISTAN":

        label = f"UZB {display_number}"

    elif player_class == "GOALKEEPER":

        label = "GK"

        if display_number > 0:
            label += f" {display_number}"

    elif player_class == "REFEREE":

        label = "REF"

    else:

        label = f"P {display_number}"


    font = cv2.FONT_HERSHEY_SIMPLEX

    font_scale = 0.55

    thickness = 2


    (text_w, text_h), baseline = cv2.getTextSize(

        label,

        font,

        font_scale,

        thickness
    )


    padding_x = 10
    padding_y = 7


    badge_w = text_w + padding_x * 2

    badge_h = text_h + padding_y * 2


    # Badge player markazida
    center_x = int(
        (x1 + x2) / 2
    )

    badge_x1 = center_x - badge_w // 2

    badge_y2 = max(
        badge_h + 5,
        y1 - 8
    )

    badge_x2 = badge_x1 + badge_w

    badge_y1 = badge_y2 - badge_h


    # -----------------------------------------
    # Dark background
    # -----------------------------------------

    cv2.rectangle(

        frame,

        (
            badge_x1,
            badge_y1
        ),

        (
            badge_x2,
            badge_y2
        ),

        (18, 18, 18),

        -1

    )


    # -----------------------------------------
    # Team color border
    # -----------------------------------------

    cv2.rectangle(

        frame,

        (
            badge_x1,
            badge_y1
        ),

        (
            badge_x2,
            badge_y2
        ),

        color,

        2

    )


    # -----------------------------------------
    # Text
    # -----------------------------------------

    cv2.putText(

        frame,

        label,

        (
            badge_x1 + padding_x,
            badge_y2 - padding_y
        ),

        font,

        font_scale,

        COLORS["WHITE"],

        thickness,

        cv2.LINE_AA
    )


