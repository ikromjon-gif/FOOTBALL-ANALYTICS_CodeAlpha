# 12. STABILIZE PLAYER CLASS
# ============================================================

def get_stable_class(track_id, detected_class):

    if track_id == -1:
        return detected_class


    if track_id not in PLAYER_HISTORY:

        PLAYER_HISTORY[track_id] = {

            "IRAN": 0,

            "UZBEKISTAN": 0,

            "GOALKEEPER": 0,

            "REFEREE": 0,

            "UNKNOWN": 0
        }


    PLAYER_HISTORY[track_id][detected_class] += 1


    # UNKNOWN juda ko'p bo'lsa ham
    # mavjud classni buzib yubormasligi uchun

    valid_classes = [
        "IRAN",
        "UZBEKISTAN",
        "GOALKEEPER",
        "REFEREE"
    ]

    best_class = max(
        valid_classes,
        key=lambda x:
        PLAYER_HISTORY[track_id][x]
    )

    best_count = PLAYER_HISTORY[track_id][best_class]


    # Hali yetarli observation bo'lmasa
    if best_count < 2:

        stable = detected_class

    else:

        stable = best_class


    PLAYER_STABLE_CLASS[track_id] = stable

    return stable


