# 11. CLASSIFY JERSEY COLOR
# ============================================================

def classify_player(frame, x1, y1, x2, y2):

    crop = get_jersey_region(
        frame,
        x1, y1, x2, y2
    )

    if crop is None:
        return "UNKNOWN"

    hsv = cv2.cvtColor(
        crop,
        cv2.COLOR_BGR2HSV
    )

    total = crop.shape[0] * crop.shape[1]

    if total == 0:
        return "UNKNOWN"


    # --------------------------------------------------------
    # WHITE - IRAN
    # --------------------------------------------------------

    white_mask = cv2.inRange(
        hsv,
        np.array([0, 0, 160]),
        np.array([180, 75, 255])
    )


    # --------------------------------------------------------
    # BLUE - UZBEKISTAN
    # --------------------------------------------------------

    blue_mask = cv2.inRange(
        hsv,
        np.array([90, 70, 40]),
        np.array([145, 255, 255])
    )


    # --------------------------------------------------------
    # LIGHT GREEN - GOALKEEPER
    # --------------------------------------------------------

    green_mask = cv2.inRange(
        hsv,
        np.array([35, 35, 70]),
        np.array([90, 255, 255])
    )


    # --------------------------------------------------------
    # RED - REFEREE
    # --------------------------------------------------------

    red1 = cv2.inRange(
        hsv,
        np.array([0, 70, 60]),
        np.array([12, 255, 255])
    )

    red2 = cv2.inRange(
        hsv,
        np.array([165, 70, 60]),
        np.array([180, 255, 255])
    )

    red_mask = cv2.bitwise_or(
        red1,
        red2
    )


    scores = {

        "IRAN":
            cv2.countNonZero(white_mask) / total,

        "UZBEKISTAN":
            cv2.countNonZero(blue_mask) / total,

        "GOALKEEPER":
            cv2.countNonZero(green_mask) / total,

        "REFEREE":
            cv2.countNonZero(red_mask) / total
    }


    best_class = max(
        scores,
        key=scores.get
    )

    best_score = scores[best_class]

    if best_score < 0.12:
        return "UNKNOWN"

    return best_class


