# 14. DRAW CLEAN PLAYER CIRCLE
# ============================================================

def draw_player_circle(
    frame,
    x1,
    y1,
    x2,
    y2,
    color
):

    player_w = x2 - x1

    foot_x = int(
        (x1 + x2) / 2
    )

    foot_y = int(y2)


    # Bitta ellipse
    ellipse_w = max(
        10,
        int(player_w * 0.32)
    )

    ellipse_h = max(
        3,
        int(ellipse_w * 0.28)
    )


    cv2.ellipse(

        frame,

        (
            foot_x,
            foot_y
        ),

        (
            ellipse_w,
            ellipse_h
        ),

        0,

        0,

        360,

        color,

        2,

        cv2.LINE_AA
    )


