# 10. JERSEY REGION
# ============================================================

def get_jersey_region(frame, x1, y1, x2, y2):

    w = x2 - x1
    h = y2 - y1

    if w < 10 or h < 20:
        return None

    # Head va shortsni chiqarib tashlaymiz
    rx1 = x1 + int(w * 0.18)
    rx2 = x2 - int(w * 0.18)

    ry1 = y1 + int(h * 0.20)
    ry2 = y1 + int(h * 0.55)

    rx1 = max(0, rx1)
    ry1 = max(0, ry1)

    rx2 = min(frame.shape[1], rx2)
    ry2 = min(frame.shape[0], ry2)

    crop = frame[ry1:ry2, rx1:rx2]

    if crop.size == 0:
        return None

    return crop


